# ============================================================
# GENERATED QUESTION → EXISTING ASSESSMENT FORMAT
# ============================================================
#
# Existing assessment system stores options as:
#
#     list[str]
#
# and correct_answer as:
#
#     str
#
# Therefore this helper converts:
#
#     [
#         {"value": "A", "text": "..."},
#         {"value": "B", "text": "..."},
#         ...
#     ]
#
# into:
#
#     ["...", "...", "...", "..."]
#
# and:
#
#     "..."
#
# without changing the existing AssessmentQuestion schema.
# ============================================================


class GeneratedAssessmentQuestionPayload(BaseModel):
    """
    Payload compatible with the existing assessment creation
    system.

    This schema is useful when the trainer approves an
    AI-generated quiz and it needs to be saved.
    """

    competency_id: int = Field(
        ...,
        gt=0,
    )

    question_text: str = Field(
        ...,
        min_length=3,
        max_length=1000,
    )

    options: list[str] = Field(
        ...,
        min_length=4,
        max_length=4,
    )

    correct_answer: str = Field(
        ...,
        min_length=1,
        max_length=255,
    )

    difficulty: str = Field(
        default="medium",
        min_length=3,
        max_length=20,
    )

    explanation: str | None = Field(
        default=None,
        max_length=2000,
    )


